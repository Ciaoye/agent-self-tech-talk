/* Presentation uses the older concise paragraphs while preserving every current
   table, diagram, image and interactive frame on its original slide. */
window.startPres = async function () {
  await window.inlineSvgReady;
  presSlides = [];
  document.querySelectorAll('.main-col section.act-section, .main-col article.slide-card').forEach(source => {
    const clone = source.cloneNode(true);
    if (source.tagName === 'SECTION') {
      clone.querySelectorAll('article.slide-card, .slide-art').forEach(node => node.remove());
      // Only the section heading and introduction belong on the chapter page.
      Array.from(clone.children).forEach(node => {
        if (!node.matches('.act-label, .act-title, .act-desc')) node.remove();
      });
      presSlides.push(clone);
      return;
    }
    const title = source.querySelector('.slide-title')?.textContent.trim();
    const old = compactTalkCopy.find(entry => entry.id === source.id && entry.title === title)
      || compactTalkCopy.find(entry => entry.id && entry.id === source.id && source.id !== 'slide-28');
    const body = clone.querySelector('.slide-body');
    if (old?.prose.length && body) {
      const current = Array.from(body.children).filter(node => node.matches('p, ul, ol') && !node.querySelector('svg, img, iframe'));
      current.forEach((node, i) => {
        if (old.prose[i]) {
          const template = document.createElement('template');
          template.innerHTML = old.prose[i];
          node.replaceWith(template.content);
        } else node.remove();
      });
      if (old.prose.length > current.length) {
        old.prose.slice(current.length).forEach(markup => body.insertAdjacentHTML('beforeend', markup));
      }
    }
    // Preserve current headings except verbose presentation-only subtitles.
    const shortTitles = {
      'slide-07': '创作的本质 · 赖声川创作金字塔',
      'slide-08': '从创作金字塔到我的系统',
      'slide-06': '规训与自我：日常里的两种逻辑',
      'slide-20': '「知道我是谁」为何更重要',
      'slide-37': '如人饮水，冷暖自知',
      'slide-42': '找到你的味道',
      'slide-47': '下一步：生命反馈引擎',
      'slide-53': '问答：感知力强，怎样开始搭建系统？'
    };
    if (shortTitles[source.id]) clone.querySelector('.slide-title').textContent = shortTitles[source.id];
    clone.querySelectorAll('iframe').forEach(frame => {
      if (frame.dataset.src) frame.src = frame.dataset.src;
      for (let parent = frame.parentElement; parent && parent !== clone; parent = parent.parentElement) {
        if (parent.style.display === 'none') parent.style.display = 'block';
      }
    });
    // Clones are independent; never mutate the article's content or assets.
    presSlides.push(clone);
  });
  presIdx = 0;
  document.body.classList.add('presenting');
  renderPres();
};
const articleRenderPres = window.renderPres;
window.renderPres = function () {
  articleRenderPres();
  document.querySelector('.pres-overlay').scrollTop = 0;
};
